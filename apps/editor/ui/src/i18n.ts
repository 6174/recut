export type I18nKey = keyof typeof zh;

export function t(
	locale: RecutLocale,
	key: I18nKey,
	params?: Record<string, string | number>,
): string {
	let text: string = messages[locale][key] ?? zh[key];
	if (params) {
		for (const [name, value] of Object.entries(params)) {
			text = text.replace(`{${name}}`, String(value));
		}
	}
	return text;
}

