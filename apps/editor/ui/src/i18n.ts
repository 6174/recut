/**
 * [INPUT]: 宿主工作台把 `?locale=zh|en` 加在 App UI iframe URL 上（无参时回退 navigator.language）。
 * [OUTPUT]: 提供 getRecutLocale() / useRecutLocale() 与 t(locale, key) 中英文字典。
 * [POS]: editor UI 的语言边界；挂载时写入 document.documentElement.lang。
 * [PROTOCOL]: 变更时更新此头部，然后检查 README.md
 */
import { useSyncExternalStore } from "react";

export type RecutLocale = "zh" | "en";

function detectLocale(): RecutLocale {
	const fromURL = new URLSearchParams(window.location.search).get("locale");
	if (fromURL === "zh" || fromURL === "en") return fromURL;
	const nav = (navigator.language || "").toLowerCase();
	return nav.startsWith("zh") ? "zh" : "en";
}

let locale: RecutLocale = detectLocale();

const SUBSCRIBERS = new Set<() => void>();

export function getRecutLocale(): RecutLocale {
	return locale;
}

function subscribe(listener: () => void) {
	SUBSCRIBERS.add(listener);
	return () => {
		SUBSCRIBERS.delete(listener);
	};
}

export function useRecutLocale(): RecutLocale {
	return useSyncExternalStore(subscribe, getRecutLocale, getRecutLocale);
}

/** 挂载时写入 <html lang>，同时通知已订阅组件刷新。 */
export function applyRecutLocale() {
	locale = detectLocale();
	document.documentElement.lang = locale === "zh" ? "zh-CN" : "en";
	for (const listener of SUBSCRIBERS) listener();
}

